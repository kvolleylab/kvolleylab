import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('./', import.meta.url));
const output = new URL('../../prototypes/member-onboarding-v1/vendor/', import.meta.url);
await mkdir(output, { recursive: true });
const packages = [
  { name: '@supabase/supabase-js', entry: '@supabase/supabase-js', exports: 'createClient', file: 'supabase-js.mjs', license: 'LICENSE' },
  { name: '@portone/browser-sdk', entry: '@portone/browser-sdk/v2', exports: 'requestIdentityVerification', file: 'portone-v2.mjs', license: 'LICENSE-MIT' },
];
const manifest = [];
const licenses = ['# Vendored browser dependencies\n\nGenerated by tools/member-onboarding/vendor.mjs.\n'];
for (const item of packages) {
  const packageDir = new URL(`node_modules/${item.name}/`, import.meta.url);
  const pkg = JSON.parse(await readFile(new URL('package.json', packageDir), 'utf8'));
  const outfile = fileURLToPath(new URL(item.file, output));
  await build({ stdin: { contents: `export { ${item.exports} } from ${JSON.stringify(item.entry)};`,
    resolveDir: root, sourcefile: `${item.file}.entry.js` }, outfile, bundle: true, minify: true,
    format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'eof' });
  const content = await readFile(outfile);
  manifest.push({ name: item.name, version: pkg.version, file: item.file,
    sha256: createHash('sha256').update(content).digest('hex') });
  licenses.push(`## ${item.name} ${pkg.version}\n\n${await readFile(new URL(item.license, packageDir), 'utf8')}\n`);
}
await writeFile(new URL('source.json', output), JSON.stringify({
  dependencies: manifest,
  note: 'PortOne npm package is the official loader; it loads the provider browser SDK when identity verification is requested. No provider script runs while identityEnabled is false.',
}, null, 2) + '\n');
await writeFile(new URL('LICENSES.md', output), licenses.join('\n'));
console.log(JSON.stringify(manifest));
