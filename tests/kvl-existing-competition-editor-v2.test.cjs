const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../prototypes/kvl-existing-competition-editor-v2.html'),'utf8');
const match=html.match(/<script>([\s\S]+)<\/script>/);
assert(match,'Embedded script missing');
const context={module:{exports:{}},URL};
vm.runInNewContext(match[1],context,{filename:'kvl-existing-competition-editor-v2.js'});
const api=context.module.exports;
const tree={tree:[{path:'data/competitions/vnl-men-2026/config.json'},{path:'data/competitions/vnl-men-2026/data.json'},{path:'data/competitions/university-goseong-men-2026/config.json'}]};
assert.deepEqual(Array.from(api.catalogFromTree(tree)),['university-goseong-men-2026','vnl-men-2026']);
assert.equal(api.validSlug('../bad'),false);
assert.equal(api.validSlug('university-goseong-men-2026'),true);
assert.equal(api.group('pro'),'pro');
assert.equal(api.group('domestic'),'domestic');
assert.equal(api.group('fivb'),'international');
assert.throws(()=>api.cleanTokens({customCSS:'*{display:none}'}),/정의되지/);
assert.throws(()=>api.cleanTokens({logoSize:999}),/허용 범위/);
assert.throws(()=>api.cleanTokens({heroColor:'red;background:red'}),/HERO 색/);
const overrides=api.normalizeOverrides({schemaVersion:2,type:'kvl-visual-overrides',global:{logoSize:40},families:{domestic:{logoSize:50,nameMode:'two'}},competitions:{'university-goseong-men-2026':{logoSize:62}}});
const config={slug:'university-goseong-men-2026',competition:{competitionFamily:'domestic',displayName:'2026 대한항공배 고성대회'}};
const data={participants:[{code:'MOK',name:'국립목포대학교',logo:'/assets/images/universities/mokpo.svg'},{code:'KIU',name:'경일대'}],matches:[{id:'M-A-01',home:{code:'MOK'},away:{code:'KIU'},score:{home:1,away:3}}],standings:{pools:[{title:'A조',rows:[{rank:1,team:{code:'KIU'},wins:2,losses:1,points:6}]}]}};
assert.equal(api.effective(overrides,config).logoSize,62);
assert.equal(api.effective(overrides,{slug:'other',competition:{competitionFamily:'domestic'}}).logoSize,50);
assert.equal(api.effective(overrides,{slug:'other',competition:{competitionFamily:'fivb'}}).logoSize,40);
assert.equal(api.chooseRows(data).name,'A조');
assert.equal(api.presentation(config,data).standings.rows[0].team.name,'경일대');
assert.equal(api.presentation(config,data).teams[0].name,'국립목포대학교');
assert.equal(api.safeAsset('/assets/images/universities/mokpo.svg'),'https://kvolleylab.com/assets/images/universities/mokpo.svg');
assert.equal(api.safeAsset('javascript:alert(1)'),'');
assert.equal(api.safeAsset('https://evil.invalid/logo.svg'),'');
const original=JSON.stringify(data);
api.safeProfile(config,data);api.presentation(config,data);api.effective(overrides,config);
assert.equal(JSON.stringify(data),original,'Source records must never mutate');
assert.throws(()=>api.safeProfile(config,{participants:null,matches:[]}),/형식/);
console.log('PASS existing competition editor v2: safety, real JSON shape, scope priority, immutable records');