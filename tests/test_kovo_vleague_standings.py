"""Behavioral safety checks for the V-league standings publication gate."""
import copy
import json
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from kovo_vleague_standings import StandingsError, calculate_standings, validate_final_match


SOURCE = ("https://user-api.kovo.co.kr/stat/league/team-rank?seasonCode=023"
          "&leagueCode=201&gender=1&round=0&page=0&size=30")
TEAMS = [{"code": code, "name": name} for code, name in
         (("AA", "가팀"), ("BB", "나팀"), ("CC", "다팀"), ("DD", "라팀"))]


def game(identifier="VL2627-M-001", home="AA", away="BB", day="2026-10-31",
         scores=((25, 20), (25, 21), (25, 22)), stage="1라운드", status="final"):
    result = {"id": identifier, "date": day, "stage": stage, "status": status,
              "home": {"code": home}, "away": {"code": away}}
    if scores is not None:
        result["score"] = {"home": sum(h > a for h, a in scores),
                           "away": sum(a > h for h, a in scores),
                           "sets": [{"home": h, "away": a} for h, a in scores]}
    return result


def by_code(result):
    return {row["team"]["code"]: row for row in result["rows"]}


def opening_snapshot():
    # Independently specified expected raw totals, not generated by the unit
    # under test. The official feed omits CC/DD because neither has played.
    return {"source_url": SOURCE, "observed_at": "2026-10-31T09:00:00Z", "rows": [
        {"team_code": "AA", "rank": 1, "played": 1, "wins": 1, "losses": 0,
         "points": 3, "sets_won": 3, "sets_lost": 0, "points_won": 75, "points_lost": 63},
        {"team_code": "BB", "rank": 2, "played": 1, "wins": 0, "losses": 1,
         "points": 0, "sets_won": 0, "sets_lost": 3, "points_won": 63, "points_lost": 75},
    ]}


class FinalValidationTests(unittest.TestCase):
    def test_valid_deuce_and_fifth_set(self):
        value = game(scores=((28, 26), (23, 25), (25, 20), (26, 28), (17, 15)))
        normalized = validate_final_match(value)
        self.assertEqual((normalized["home"], normalized["away"]), (3, 2))
        self.assertEqual(normalized["sets"][-1], {"home": 17, "away": 15})
        normalized["sets"][0]["home"] = 999
        self.assertEqual(value["score"]["sets"][0]["home"], 28)

    def test_set_must_stop_at_first_legal_winning_score(self):
        for invalid in ((24, 22), (25, 24), (26, 23), (30, 27), (25, 25)):
            with self.subTest(score=invalid), self.assertRaises(StandingsError):
                validate_final_match(game(scores=(invalid, (25, 20), (25, 20))))

    def test_fifth_set_uses_15_point_target(self):
        for invalid in ((14, 12), (15, 14), (16, 13), (25, 20)):
            with self.subTest(score=invalid), self.assertRaises(StandingsError):
                validate_final_match(game(scores=((25, 20), (20, 25), (25, 20), (20, 25), invalid)))

    def test_final_score_must_match_set_winners(self):
        value = game(scores=((25, 20), (20, 25), (25, 20)))
        value["score"]["home"], value["score"]["away"] = 3, 0
        with self.assertRaisesRegex(StandingsError, "set winners"):
            validate_final_match(value)

    def test_no_sets_after_third_win(self):
        value = game(scores=((25, 20), (25, 20), (25, 20), (20, 25)))
        with self.assertRaisesRegex(StandingsError, "already ended"):
            validate_final_match(value)

    def test_missing_set_points_are_not_zero_filled(self):
        for missing in (None, [], [{"home": 25, "away": 20}]):
            value = game()
            value["score"]["sets"] = missing
            with self.subTest(sets=missing), self.assertRaises(StandingsError):
                validate_final_match(value)

    def test_strict_integer_points_and_set_counts(self):
        for invalid in (True, "25", -1, 25.0, None):
            value = game()
            value["score"]["sets"][0]["home"] = invalid
            with self.subTest(value=invalid), self.assertRaises(StandingsError):
                validate_final_match(value)
        value = game()
        value["score"]["home"] = 3.0
        with self.assertRaises(StandingsError):
            validate_final_match(value)

    def test_explicit_final_status_and_completion_required(self):
        for status in (None, "live", "scheduled", "finished"):
            with self.subTest(status=status), self.assertRaises(StandingsError):
                validate_final_match(game(status=status))
        value = game()
        value["score"]["sets"][0]["complete"] = False
        with self.assertRaises(StandingsError):
            validate_final_match(value)


class CalculationTests(unittest.TestCase):
    def test_three_zero_totals_and_zero_denominators(self):
        result = calculate_standings(TEAMS, [game()])
        rows = by_code(result)
        self.assertEqual((rows["AA"]["wins"], rows["BB"]["losses"]), (1, 1))
        self.assertEqual((rows["AA"]["points"], rows["BB"]["points"]), (3, 0))
        self.assertEqual((rows["AA"]["setRatio"], rows["BB"]["setRatio"]), ("MAX", "0.000"))
        self.assertEqual((rows["AA"]["pointsFor"], rows["AA"]["pointsAgainst"]), (75, 63))
        self.assertEqual(rows["AA"]["pointRatio"], "1.190")
        self.assertEqual(rows["CC"]["setRatio"], "-")
        self.assertIsNone(rows["CC"]["rank"])
        json.dumps(result, allow_nan=False)

    def test_three_two_distributes_two_and_one_points(self):
        value = game(scores=((28, 26), (23, 25), (25, 20), (26, 28), (17, 15)))
        rows = by_code(calculate_standings(TEAMS, [value]))
        self.assertEqual((rows["AA"]["points"], rows["BB"]["points"]), (2, 1))
        self.assertEqual((rows["AA"]["setWins"], rows["AA"]["setLosses"]), (3, 2))
        self.assertEqual(rows["AA"]["pointsFor"], 119)
        self.assertEqual(rows["BB"]["pointsFor"], 114)

    def test_three_one_away_win(self):
        value = game(scores=((20, 25), (25, 21), (20, 25), (20, 25)))
        rows = by_code(calculate_standings(TEAMS, [value]))
        self.assertEqual((rows["BB"]["wins"], rows["AA"]["losses"]), (1, 1))
        self.assertEqual((rows["BB"]["points"], rows["AA"]["points"]), (3, 0))
        self.assertEqual(rows["BB"]["setRatio"], "3.000")

    def test_scheduled_live_and_postseason_never_count(self):
        fixtures = [game(scores=None, status="scheduled"),
                    game("next", "CC", "DD", scores=((25, 20),), status="live"),
                    game("postseason", day="2027-04-01", stage="챔피언결정전")]
        fixtures[0].pop("status")  # Existing KVL schedule shape.
        result = calculate_standings(TEAMS, fixtures)
        self.assertEqual(result["counted_match_ids"], [])
        self.assertEqual(len(result["excluded_match_ids"]), 3)
        self.assertTrue(all(row["games"] == 0 and row["rank"] is None for row in result["rows"]))
        self.assertFalse(result["review_required"])

    def test_unrecognized_stage_requires_review(self):
        result = calculate_standings(TEAMS, [game(stage="정규리그")])
        self.assertTrue(result["review_required"])
        self.assertEqual(result["issues"][0]["code"], "UNRECOGNIZED_STAGE")
        self.assertEqual(result["counted_match_ids"], [])

    def test_legacy_score_and_scheduled_score_require_review(self):
        for status in (None, "scheduled", "cancelled", "postponed"):
            with self.subTest(status=status), self.assertRaises(StandingsError):
                calculate_standings(TEAMS, [game(status=status)])

    def test_duplicate_match_ids_and_identity_rejected(self):
        original = game()
        cases = [copy.deepcopy(original), game("different-id"),
                 game("reversed", "BB", "AA")]
        for duplicate in cases:
            with self.subTest(id=duplicate["id"]), self.assertRaisesRegex(StandingsError, "duplicate match"):
                calculate_standings(TEAMS, [original, duplicate])

    def test_duplicate_source_match_keys_rejected(self):
        a, b = game(), game("different", day="2026-11-01")
        a["source_key"] = b["source_key"] = "023:201:1:1"
        with self.assertRaisesRegex(StandingsError, "source match"):
            calculate_standings(TEAMS, [a, b])

    def test_bad_team_and_date_identities_rejected(self):
        for fixture in (game(home="XX"), game(away="AA"), game(day="2026-02-30")):
            with self.subTest(fixture=fixture), self.assertRaises(StandingsError):
                calculate_standings(TEAMS, [fixture])
        with self.assertRaisesRegex(StandingsError, "duplicate participant"):
            calculate_standings(TEAMS + [TEAMS[0]], [game()])

    def test_no_source_no_verified_rules_means_no_claimed_ranks(self):
        result = calculate_standings(TEAMS, [game()])
        self.assertTrue(result["review_required"])
        self.assertTrue(all(row["rank"] is None for row in result["rows"]))
        self.assertEqual(result["rule_provenance"]["formal_rules_status"], "NOT_VERIFIED")

    def test_exact_ties_remain_ties_without_alphabetical_resolution(self):
        teams = [TEAMS[1], TEAMS[0], TEAMS[2], TEAMS[3]]
        fixtures = [game("one", "AA", "CC"), game("two", "BB", "DD")]
        result = calculate_standings(teams, fixtures, rules_verified=True)
        rows = by_code(result)
        self.assertEqual((rows["AA"]["rank"], rows["BB"]["rank"]), (1, 1))
        self.assertEqual((rows["CC"]["rank"], rows["DD"]["rank"]), (3, 3))
        self.assertEqual([row["team"]["code"] for row in result["rows"][:2]], ["BB", "AA"])
        self.assertTrue(result["review_required"])
        self.assertEqual(len(result["issues"]), 2)

    def test_sort_uses_exact_ratios_not_rounded_display(self):
        fixtures = [game("one", "AA", "CC", scores=((1000, 998),) * 3),
                    game("two", "BB", "DD", scores=((1001, 999),) * 3)]
        rows = by_code(calculate_standings(TEAMS, fixtures, rules_verified=True))
        self.assertEqual(rows["AA"]["pointRatio"], rows["BB"]["pointRatio"])
        self.assertLess(rows["AA"]["rank"], rows["BB"]["rank"])

    def test_inputs_are_not_mutated(self):
        fixtures = [game()]
        before = copy.deepcopy((TEAMS, fixtures))
        calculate_standings(TEAMS, fixtures, official_ranks=opening_snapshot())
        self.assertEqual((TEAMS, fixtures), before)

    def test_candidate_criteria_are_points_then_wins_then_set_quotient(self):
        five = ((25, 20), (20, 25), (25, 20), (20, 25), (15, 10))
        fixtures = [game(f"a-{i}", "AA", "CC", day=f"2026-11-{i + 1:02d}")
                    for i in range(3)]
        fixtures += [game(f"b-{i}", "BB", "DD", day=f"2026-11-{i + 1:02d}", scores=five)
                     for i in range(4)]
        rows = by_code(calculate_standings(TEAMS, fixtures, rules_verified=True))
        self.assertEqual((rows["AA"]["points"], rows["BB"]["points"]), (9, 8))
        self.assertEqual((rows["AA"]["wins"], rows["BB"]["wins"]), (3, 4))
        self.assertLess(rows["AA"]["rank"], rows["BB"]["rank"])
        # At six points each, the three five-set wins precede two sweeps.
        fixtures = [m for m in fixtures if m["id"] not in ("a-2", "b-3")]
        rows = by_code(calculate_standings(TEAMS, fixtures, rules_verified=True))
        self.assertEqual((rows["AA"]["points"], rows["BB"]["points"]), (6, 6))
        self.assertLess(rows["BB"]["rank"], rows["AA"]["rank"])
        # Set quotient precedes point quotient, unlike the KUSF comparator.
        fixtures = [game("a", "AA", "CC", scores=((25, 23),) * 3),
                    game("b", "BB", "DD", scores=((0, 25), (25, 0), (25, 0), (25, 0)))]
        rows = by_code(calculate_standings(TEAMS, fixtures, rules_verified=True))
        self.assertEqual((rows["AA"]["points"], rows["BB"]["points"]), (3, 3))
        self.assertGreater(float(rows["BB"]["pointRatio"]), float(rows["AA"]["pointRatio"]))
        self.assertLess(rows["AA"]["rank"], rows["BB"]["rank"])

    def test_zero_conceded_points_is_json_safe(self):
        rows = by_code(calculate_standings(TEAMS, [game(scores=((25, 0),) * 3)]))
        self.assertEqual(rows["AA"]["pointRatio"], "MAX")
        self.assertEqual(rows["BB"]["pointRatio"], "0.000")
        json.dumps(rows, allow_nan=False)


class OfficialReconciliationTests(unittest.TestCase):
    def test_empty_preseason_official_snapshot(self):
        result = calculate_standings(TEAMS, [game(scores=None, status="scheduled")],
                                     official_ranks={"source_url": SOURCE, "rows": []})
        self.assertFalse(result["review_required"])
        self.assertTrue(all(row["rank"] is None for row in result["rows"]))

    def test_reconciled_official_rank_is_authoritative_with_unplayed_teams(self):
        result = calculate_standings(TEAMS, [game()], official_ranks=opening_snapshot())
        self.assertFalse(result["review_required"])
        self.assertEqual([row["rank"] for row in result["rows"]], [1, 2, None, None])
        self.assertEqual(result["rule_provenance"]["basis"], "OFFICIAL_SNAPSHOT_RECONCILED")
        self.assertEqual(result["rule_provenance"]["formal_rules_status"], "NOT_VERIFIED")
        self.assertEqual(result["rule_provenance"]["official_standings_source_url"], SOURCE)

    def test_every_raw_total_must_reconcile(self):
        for field in ("played", "wins", "losses", "points", "sets_won", "sets_lost", "points_won", "points_lost"):
            snapshot = opening_snapshot()
            snapshot["rows"][0][field] += 1
            with self.subTest(field=field), self.assertRaisesRegex(StandingsError, "mismatch"):
                calculate_standings(TEAMS, [game()], official_ranks=snapshot)

    def test_missing_extra_duplicate_and_stale_standings_rows_fail(self):
        missing = opening_snapshot()
        missing["rows"].pop()
        extra = opening_snapshot()
        extra["rows"].append(dict(extra["rows"][0], team_code="CC", rank=3))
        duplicate = opening_snapshot()
        duplicate["rows"].append(copy.deepcopy(duplicate["rows"][0]))
        for snapshot in (missing, extra, duplicate):
            with self.subTest(snapshot=snapshot), self.assertRaises(StandingsError):
                calculate_standings(TEAMS, [game()], official_ranks=snapshot)
        # A second final that the standings endpoint has not caught up with.
        with self.assertRaisesRegex(StandingsError, "mismatch"):
            calculate_standings(TEAMS, [game(), game("second", day="2026-11-02")],
                                official_ranks=opening_snapshot())

    def test_invalid_rank_and_wrong_source_are_rejected(self):
        for rank in (0, True, "1", 2, 5):
            snapshot = opening_snapshot()
            snapshot["rows"][0]["rank"] = rank
            with self.subTest(rank=rank), self.assertRaises(StandingsError):
                calculate_standings(TEAMS, [game()], official_ranks=snapshot)
        for source in (SOURCE.replace("023", "022"), SOURCE.replace("round=0", "round=1"),
                       SOURCE.replace("user-api.kovo.co.kr", "example.com")):
            snapshot = opening_snapshot()
            snapshot["source_url"] = source
            with self.subTest(source=source), self.assertRaises(StandingsError):
                calculate_standings(TEAMS, [game()], official_ranks=snapshot)

    def test_official_order_may_resolve_a_real_numeric_tie(self):
        teams = TEAMS[:2]
        fixtures = [game(), game("return", "BB", "AA", day="2026-11-01")]
        snapshot = {"source_url": SOURCE, "rows": [
            {"team_code": code, "rank": rank, "played": 2, "wins": 1, "losses": 1,
             "points": 3, "sets_won": 3, "sets_lost": 3, "points_won": 138, "points_lost": 138}
            for code, rank in (("BB", 1), ("AA", 2))]}
        result = calculate_standings(teams, fixtures, official_ranks=snapshot)
        self.assertFalse(result["review_required"])
        self.assertEqual([row["team"]["code"] for row in result["rows"]], ["BB", "AA"])


if __name__ == "__main__":
    unittest.main()
