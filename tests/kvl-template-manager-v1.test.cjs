const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../prototypes/kvl-template-manager-v1.html'),'utf8');
const script=html.match(/<script defer>([\s\S]*?)<\/script>/);
assert(script,'standalone prototype must embed its JavaScript');
const context={module:{exports:{}}};
vm.runInNewContext(script[1],context,{filename:'kvl-template-manager-v1.js'});
const {sampleState,parseCSV,importMatchesCSV,validate,validDate}=context.module.exports;
const s=sampleState();
assert.equal(validate(s.config,s.data).valid,true);
assert.equal(validDate('2027-02-29'),false);
assert.equal(validDate('2028-02-29'),true);
const rows=parseCSV('\ufeffid,date,home,away,venue\r\nM01,2027-06-01,T01,T02,"체육관, A"\r\nM02,2027-06-02,T03,T04,"두 줄\n경기장"\r\n');
assert.equal(rows.length,3);
assert.equal(rows[1][4],'체육관, A');
assert.equal(rows[2][4],'두 줄\n경기장');
const csv='id,date,time,stage,home,away,venue,homeScore,awayScore\nM03,2027-06-02,14:00,예선,T01,T03,샘플 체육관,3,1';
const added=importMatchesCSV(csv,s.data.matches);
assert.equal(added.length,1);
assert.equal(added[0].scoreVerification,false);
assert.equal(added[0].status,'pending_review');
s.data.matches.push(...added);s.data.matchCount++;
assert.equal(validate(s.config,s.data).valid,true);
assert(validate(s.config,s.data).warnings.some(w=>w.includes('공식 근거')));
assert.throws(()=>importMatchesCSV(csv,s.data.matches),/중복/);
assert.throws(()=>importMatchesCSV('bad,head\n1,2',[]),/필수/);
s.data.matches[0].away.code='BAD';
assert.equal(validate(s.config,s.data).valid,false);
s.data.matches[0].away.code='T02';
s.data.matches[0].score={home:3,away:3};
assert.equal(validate(s.config,s.data).valid,false);
console.log('PASS: standalone code, dates, CSV quoting, duplicate IDs, team links, invalid scores');
